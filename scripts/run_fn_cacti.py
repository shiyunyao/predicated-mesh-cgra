CLOCK_HZ = 100_000_000
SCENARIO = "all_declared_ports_once_per_10ns_cycle"
FNC_DEVICE_NODE_UM = 0.014
FNC_WIRE_NODE_UM = 0.007
FNC_OPERATING_VOLTAGE = 0.7
FNC_MINIMUM_CAPACITY_BYTES = 64
PROXY_STATUS = "MEMORY_PPA_COMPLETE_ANALYTICAL_PROXY"


def architectural_size_bytes(storage: dict[str, Any]) -> int:
    return (storage["width_bits"] * storage["depth"] + 7) // 8


def modeled_size_bytes(storage: dict[str, Any]) -> int:
    return max(architectural_size_bytes(storage), FNC_MINIMUM_CAPACITY_BYTES)


def class_model_status(storage: dict[str, Any]) -> str:
    if modeled_size_bytes(storage) != architectural_size_bytes(storage):
        return "MODELED_WITH_ASYNC_READ_AND_MINIMUM_CAPACITY_PADDING_APPROXIMATION"
    return "MODELED_WITH_EXPLICIT_ASYNC_READ_APPROXIMATION"


def model_basis() -> dict[str, Any]:
    return {
        "architectural_technology": "ASAP7_7NM",
        "fn_cacti_transistor_type": "finfet",
        "fn_cacti_device_node_um": FNC_DEVICE_NODE_UM,
        "fn_cacti_wire_node_um": FNC_WIRE_NODE_UM,
        "fn_cacti_interconnects": "ASAP7",
        "operating_voltage_v": FNC_OPERATING_VOLTAGE,
        "scaling_applied": False,
        "logic_area_compatibility": "INCOMPATIBLE_WITH_ASAP7_7NM_1X_LOGIC_AREA",
        "reason": (
            "the supplied FN-CACTI README documents 14 nm device support; its 7 nm "
            "device-node probe aborts in component.cc, so no 7 nm device proxy is accepted"
        ),
    }


def write_text(path: pathlib.Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def run_to_log(command: list[str], cwd: pathlib.Path, log_path: pathlib.Path) -> int:
    with log_path.open("w", encoding="utf-8") as log:
        completed = subprocess.run(
            command,
            cwd=cwd,
            check=False,
            stdout=log,
            stderr=subprocess.STDOUT,
            text=True,
        )
    return completed.returncode


